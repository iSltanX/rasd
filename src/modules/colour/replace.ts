/**
 * الاستبدال المؤقّت — أربعة أوضاع، ولا واحد منها يلمس ملفّ مشروع (`§6.11`).
 *
 * «عنصر واحد» و«كل المطابقات» تحت دالّة واحدة (`replaceOnElements`): كلاهما
 * الآلية نفسها حرفيًّا — كتابة سطرية على قائمة عناصر — والفرق بينهما عدد
 * العناصر في القائمة لا منطق مختلف. `scope` النتيجة يُشتقّ من طول القائمة:
 * عنصر واحد بالضبط ← `'element'`، وأيّ عددٍ آخر (بما فيه صفر) ← `'matches'`.
 * حالة نادرة — بحث «كل المطابقات» يعثر على مطابقة واحدة بالصدفة — تُوسَم
 * `'element'` رغم أنها جاءت من مسار المطابقة؛ هذا تصنيفٌ لا سلوك، ولا يغيّر
 * ما يقع على الصفحة.
 *
 * **الكتابة نصّية بـ`setAttribute('style', …)`، لا عبر `el.style.xxx`.**
 * القياس منقول من `content/tools/full-page.ts` (اقرأ تعليق `applyTile`
 * هناك): أي لمس لـ`CSSStyleDeclaration` يجعل `removeAttribute('style')`
 * لاحقًا يترك سمةً **فارغة** لا يحذفها — عنصر بلا نمط سطري أصلًا ينتهي
 * بـ`style=""`. هذا الاختبار («بلا أثر متبقٍّ») يفرضه `§14` نصًّا، فتجنّب هذا
 * الخطأ بعينه هو صلب الوحدة لا تفصيل تنفيذي.
 *
 * **الأسبقية: `!important` على كل تصريح نحقنه، لا ترتيب الإدراج ولا خصوصية
 * محدِّد.** نصّ الخطّة يقول «بأسبقية عالية» بلا تحديد آلية. ترتيب الإدراج
 * وحده هشّ: أي سكربت صفحة يُدرِج ورقة بعدنا يفوز. وخصوصية المحدِّد كذلك: صفحة
 * تكتب `#id.class[attr]{color:...}` تفوز على `:root{...}` عاديّة. أمّا
 * `!important` فيفوز على أي تصريح غير `!important` من نفس الأصل (author)
 * **بصرف النظر عن الخصوصية** — وهو ترتيب طبقات الـcascade نفسه (الأهمّية
 * أعلى من الخصوصية)، مُثبَت في تعليق `probe` أدناه: نمط سطري `!important`
 * يهزم قاعدة ورقة بمحدِّد صنف تحمل `!important` هي الأخرى. الاحتمال الوحيد
 * الباقي — أن تكتب الصفحة تصريحًا أعلى خصوصيةً **و**`!important` هو الآخر —
 * نادر بما يكفي ليبقى حدًّا معلَنًا لا مُعالَجًا (لا وجود لحرب أسبقية أعقد من
 * هذا في أي صفحة اختُبرت أثناء بناء الوحدة).
 *
 * **الخاصية معامل صريح، لا تُخمَّن.** اللون قد يُستعمَل في `color` أو
 * `background-color` أو أيّ حدّ من الحدود الأربعة أو `fill`/`stroke` أو
 * `box-shadow`/`text-shadow` — و`usage.ts` (المجاور) هو من يعرف أيّها، من
 * نتيجة المسح (`UsageMatch.property`). هذه الوحدة **تكتب ما يُمرَّر إليها
 * حرفيًّا** ولا تفهم دلالته: لخاصية مفردة اللون (`color`) القيمة هي اللون
 * نفسه، ولخاصية مركّبة (`box-shadow`) القيمة يجب أن تكون **تصريح الخاصية
 * كاملًا** لا اللون وحده — تفكيك الظلّ وإعادة تركيبه بلون جديد مسؤولية
 * المستدعي إن لزم، لا هذه الوحدة. وبالمثل `colour` نصّ CSS جاهز (ناتج
 * `formatColour` أو مكافئه) لا `ColourReading` — فالوحدة كتابة DOM خالصة، لا
 * تعرف تمثيل اللون الداخلي، ولا تستورد شيئًا من بقيّة `colour/*`.
 *
 * **أين تُحقَن ورقة المتغيّر؟ `document.head` (أو `documentElement` حين
 * يغيب، دفاعًا لا توقّعًا).** والسؤال الأهمّ: هل تعبر جذور الظلّ؟ **نعم —
 * خلافًا لورقة `full-page.ts`، ولسبب مختلف جوهريًّا.** ورقة تلك تعتمد
 * **مطابقة محدِّدات** (`* {...}`)، والمحدِّدات لا تعبر حدّ الظلّ أبدًا — قِيس
 * هنا أيضًا: قاعدة صنف في ورقة الرأس لا تصل عنصرًا داخل جذر ظلّ. لكن متغيّرًا
 * مُعاد تعريفه عند `:root` لا يعتمد مطابقة محدِّدات ليصل: خصائص CSS
 * المخصَّصة **موروثة** كأي خاصية موروثة أخرى (`color` مثلًا)، والوراثة تعبر
 * حدّ الظلّ من المضيف إلى شجرته دومًا — وهذا مُقاس هنا حرفيًّا (بيئة
 * الاختبار وسلوك المواصفة متّفقان: هذه هي الحيلة القياسية لتمرير سمات
 * التصميم عبر مكوّنات ويب، لا خاصّية عرضية لبيئة الاختبار). **الحدّ الحقيقي
 * الباقي**: عنصر داخل جذر ظلّ يُعيد تعريف **المتغيّر نفسه** على نطاق أضيق
 * (`:host{--x:...}` أو أي سلف داخل الشجرة نفسها) لا يتأثّر بإعادة تعريفنا —
 * وهذا سلوك الوراثة الطبيعي (أقرب تعريف يفوز) لا قصورًا في الحقن.
 *
 * **العناصر التي تختفي من DOM قبل `revert()` لا تُكسِر شيئًا.** `setAttribute`
 * و`getAttribute` و`removeAttribute` تعمل على عنصر منفصل عن الشجرة بلا أي
 * شرط اتصال — والمرجع الذي نحمله في `Map` يبقى صالحًا حتى لو أزالته الصفحة
 * من DOM. `revert()` يُطبَّق على القائمة المحفوظة وقت الاستدعاء، تمامًا كما
 * تفعل `finishFullPage` هناك على `session.saved` لا على مسح جديد.
 *
 * `modules/` منطق خالص فوق `shared/` من حيث الاستيراد، لكن لمس DOM هنا
 * مشروع على سابقة `background.ts` و`dom-picker/inspect.ts` في هذا الشجرة:
 * كل دالّة تلمس نافذة تأخذها معامَلًا صريحًا بقيمة افتراضية
 * (`win: Window = globalThis.window`)، لا عامًّا عالميًّا — شرط قابلية
 * الاختبار في happy-dom. `replaceOnElements` وحدها استثناء لهذا: عملياتها
 * كلّها على مراجع عناصر مباشرة (`setAttribute`/`getAttribute`)، فلا تلمس
 * `document` ولا `getComputedStyle` أصلًا — معامل نافذة فيها كان سيكون
 * معامَلًا ميتًا (والمشروع يفرض `noUnusedParameters`).
 */

/** الأوضاع الثلاثة التي تُنتج مقبضًا؛ «التراجع/إعادة الضبط» فعل لا وضع. */
export type ReplaceScope = 'element' | 'matches' | 'variable'

export interface ReplaceHandle {
  readonly scope: ReplaceScope
  /**
   * يُعيد الصفحة إلى ما كانت عليه بالضبط. آمنٌ للاستدعاء مرّتين: الاستدعاء
   * الثاني لا يفعل شيئًا (حارس `reverted` داخلي)، لا لأن العمليات نفسها غير
   * قابلة للتكرار — `setAttribute`/`Element.remove()` كلاهما مثاليّ التكرار
   * أصلًا — بل لأن الحارس يمنع أثرًا جانبيًّا أدقّ: استدعاءً ثانيًا بعد أن
   * عدّل مستدعٍ آخر العنصر نفسه كان سيمحو ذلك التعديل اللاحق سهوًا.
   */
  revert(): void
}

/** سمة تُعلِّم ورقة المتغيّر المحقونة — لتشخيص الاختبار، لا لوظيفة. */
export const VARIABLE_STYLE_MARKER = 'data-rasd-colour-replace-variable'

/**
 * كل المقابض الحيّة، بترتيب الإنشاء — يخدم `revertAll` وحدها.
 *
 * `Set` لا مصفوفة: كل مقبض يحذف نفسه عند `revert()` الفردي (`O(1)`)، فلا
 * يبقى في `revertAll` مقبض سبق التراجع عنه يُعاد التراجع عنه (حارس `reverted`
 * الداخلي يجعل ذلك غير ضارّ على أي حال، لكن الحذف يبقي المجموعة معبِّرة عن
 * «الفعليّ الحيّ» لا سجلًّا تاريخيًّا متضخّمًا).
 */
const active = new Set<ReplaceHandle>()

/**
 * نصّ `style` بعد إلحاق تصريحنا — أو تصريحنا وحده حين لا نمط أصليًّا.
 *
 * فراغ نصّي أصلي (`style=""`، سمة موجودة بقيمة فارغة) **حالة مختلفة عن
 * غياب السمة** (`null`) — `base` هنا فارغ فيسقط من الإلحاق (`base ? … : …`)
 * فلا يُنتج فاصلةً منقوطة زائدة، لكن `saved` في المستدعي يحفظ الفراغ نصًّا
 * لا `null`، فتعود السمة الفارغة فارغةً بالضبط عند `revert()` لا تختفي.
 */
function withDeclaration(base: string | null, property: string, colour: string): string {
  const decl = `${property}:${colour}!important`
  return base ? `${base};${decl}` : decl
}

/**
 * استبدال سطري على قائمة عناصر — «عنصر واحد» و«كل المطابقات» معًا (انظر
 * ترويسة الملفّ لتعليل الدمج). مرحلتان منفصلتان — قراءة الكلّ ثم كتابة
 * الكلّ — لا مرحلة واحدة مدموجة: عنصر مكرَّر في `els` (خطأ مستدعٍ لا حالة
 * متوقَّعة، لكنها رخيصة الدرء) كان سيقرأ نمطًا **بعد** تعديله لو دُمجتا،
 * فيحفظ أصلًا خاطئًا ويُفسد `revert()`.
 */
export function replaceOnElements(
  els: readonly Element[],
  property: string,
  colour: string,
): ReplaceHandle {
  const scope: ReplaceScope = els.length === 1 ? 'element' : 'matches'
  const saved = new Map<Element, string | null>()
  for (const el of els) saved.set(el, el.getAttribute('style'))
  for (const el of els) {
    el.setAttribute('style', withDeclaration(saved.get(el) ?? null, property, colour))
  }

  let reverted = false
  const handle: ReplaceHandle = {
    scope,
    revert(): void {
      if (reverted) return
      reverted = true
      for (const [el, raw] of saved) {
        if (raw === null) el.removeAttribute('style')
        else el.setAttribute('style', raw)
      }
      active.delete(handle)
    },
  }
  active.add(handle)
  return handle
}

/**
 * استبدال متغيّر CSS كامل — الوضع «الأقوى» بنصّ الخطّة: تغيير `--x` يعيد
 * طلاء كل مستخدميه دفعة واحدة، بلا مسح DOM ولا قائمة عناصر.
 *
 * ورقة واحدة لكل استدعاء، تُعلَّم بـ`VARIABLE_STYLE_MARKER` (قيمتها اسم
 * المتغيّر، مفيد عند تشخيص عدّة استبدالات متزامنة). `revert()` يحذف عقدة
 * `<style>` بعينها المُنشأة هنا — لا يبحث عنها بالسمة وقت التراجع — فحتى لو
 * حقن استدعاءٌ آخر ورقةً بالاسم نفسه، لا التباس في أيّهما تُحذَف.
 */
export function replaceVariable(
  name: string,
  colour: string,
  win: Window = globalThis.window,
): ReplaceHandle {
  const doc = win.document
  const style = doc.createElement('style')
  style.setAttribute(VARIABLE_STYLE_MARKER, name)
  style.textContent = `:root{${name}:${colour}!important}`
  ;(doc.head ?? doc.documentElement).appendChild(style)

  let reverted = false
  const handle: ReplaceHandle = {
    scope: 'variable',
    revert(): void {
      if (reverted) return
      reverted = true
      style.remove()
      active.delete(handle)
    },
  }
  active.add(handle)
  return handle
}

/**
 * التراجع/إعادة الضبط — يُلغي كل استبدال حيّ من هذه الوحدة، بأيّ وضع أُنشئ.
 *
 * **بترتيب عكسيّ لترتيب الإنشاء (LIFO).** مقبضان تداخلا على العنصر نفسه
 * (مستخدم بدّل عنصرًا بلونٍ ثم بدّله بلون آخر بمقبض ثانٍ بلا تراجع عن
 * الأوّل) يحملان كلٌّ نسخته الخاصّة من «قبلي» — والتراجع بالترتيب العكسي
 * وحده يضمن العودة إلى الأصل الحقيقي للصفحة: تراجعٌ بالترتيب الأمامي كان
 * سيُطبِّق تراجع المقبض الأوّل فوق تعديل الثاني القائم فعلًا، فيمحو تعديل
 * الثاني بدل التراجع عنه بنظام.
 */
export function revertAll(): void {
  for (const handle of [...active].reverse()) handle.revert()
}
