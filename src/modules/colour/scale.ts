/**
 * سلّم الدرجات 50→950، وأربعة تعديلات مفردة — «نفس المنهج المستخدم في
 * نظام رصد نفسه» (`Rasd_Plan.md §14`, `§6.12`).
 *
 * **المنهج مُستنبَط من `public/assets/tokens.css` لا مُخترَع.** حُوِّلت
 * السلاسل السداسية للعائلات التسع الملوَّنة (`signal`·`ember`·`measure`·
 * `inspect`·`success`·`warning`·`danger`·`info`، وعائلة `ink` الرمادية)
 * إلى OKLCH بالتحويل نفسه هنا، وقِيس أمران:
 *
 *   1. **الإضاءة (`l`) على شبكة واحدة تتقاسمها كل العائلات.** وسيط كل درجة
 *      عبر التسع عائلات الملوَّنة (بالنسبة المئوية)، والانحراف المعياري
 *      لا يتجاوز 0.13 نقطة في أسوأ درجة — عمليًّا شبكة واحدة:
 *
 *      | الدرجة | 50 | 100 | 200 | 300 | 400 | 500 | 600 | 700 | 800 | 900 | 950 |
 *      |---|---|---|---|---|---|---|---|---|---|---|---|
 *      | `L%` | 97.53 | 94.53 | 88.99 | 82.00 | 74.05 | 65.54 | 57.46 | 49.04 | 40.03 | 31.03 | 24.08 |
 *
 *   2. **التشبّع (`c`) مقصوصٌ على حدّ مدى sRGB عند تلك الإضاءة والزاوية —
 *      لا رقمًا مستقلًّا.** أُعيد حساب أقصى تشبّع ممكن في sRGB لكل (`l`,`h`)
 *      عبر بحثٍ ثنائي (`clampChroma`، انظر أدناه)، وقورن بالقيمة الفعلية في
 *      `tokens.css`: **كل درجة من كل عائلة تطابق حدّها الأقصى ضمن %0.1 —
 *      أي أنها على حافة المدى بالضبط**، لا نسبة ثابتة منه. مثال مقيس
 *      (عائلة `info`، بزاوية كل درجة الفعلية بعد التقريب السداسي):
 *
 *      | الدرجة | `L` | `h` الفعلية | `c` في tokens.css | أقصى تشبّع محسوب |
 *      |---|---|---|---|---|
 *      | 500 | 65.52% | 251.97° | 0.1892 | 0.1892 |
 *      | 800 | 40.03% | 252.29° | 0.1208 | 0.1208 |
 *      | 950 | 23.98% | 253.19° | 0.0744 | 0.0744 |
 *
 *      والزاوية (`h`) شبه ثابتة داخل العائلة الواحدة (انحراف 1°–3° فقط —
 *      أثر تقريب OKLCH إلى بايت سداسي عشري ثم عودته، لا تصميم مقصود)،
 *      فتُقرأ النتيجة: **زاوية واحدة تقريبًا لكل عائلة، وتشبّع كل درجة هو
 *      الحدّ الأقصى الذي يحتمله sRGB عند إضاءتها**.
 *
 * فالسلّم هنا يطبّق الشيء نفسه على أي لون أساس: **زاوية ثابتة (زاوية
 * الأساس)**، **إضاءة الشبكة أعلاه**، و**تشبّع مقيَّد بحافة sRGB عند تلك
 * النقطة، مضروبًا في نسبة تشبّع الأساس إلى حافته هو** — لا حافة كاملة
 * دائمًا، وإلا لَحُذِف تشبّع الأساس الذي اختاره المستخدم فعليًا. التفصيل
 * والتعليل الكامل عند `generateScale` أدناه.
 *
 * **الفرق بين هذا الملفّ و`tailwind.ts`**: ذاك يُسمّي لونًا قائمًا بأقرب
 * درجة في لوحة جاهزة؛ هذا **يُنتج** لوحة كاملة من لون واحد. ولا علاقة
 * وظيفية بينهما تستدعي دالّة مشتركة.
 *
 * `modules/` منطق خالص: لا DOM ولا `chrome.*`.
 */

import { clampChroma, modeOklch, modeRgb, useMode } from 'culori/fn'

import { formatColour, fromOklch, type ColourReading, type Oklch } from './formats'

/*
 * `formats.ts` يسجّل `rgb`/`oklch` عند تحميله، وهذه الوحدة تستورد منه —
 * فالتسجيل يقع فعلًا قبل وصول التنفيذ هنا. ومع ذلك تُسجَّل الوضعان هنا
 * صراحةً أيضًا، على نمط `tailwind.ts` («rgb/oklab يسجّلهما distance.ts؛
 * وoklch يلزم هنا لقراءة قيم اللوحة نفسها»): هذا الملفّ يستعمل الوضعين
 * مباشرةً (`clampChroma` بوضع `oklch`، وحافة `rgb`)، فلا يصحّ أن يعتمد على
 * ترتيب استيراد ملفّ آخر ليعمل.
 */
useMode(modeRgb)
useMode(modeOklch)

const clamp01 = (v: number): number => Math.min(1, Math.max(0, v))

/** السلّم الكامل — 11 درجة، مطابقة لأسماء درجات `tokens.css` بالضبط. */
export const SCALE_STEPS: readonly number[] = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]

/**
 * شبكة الإضاءة المشتركة — `l` بمدى 0..1، بترتيب `SCALE_STEPS` نفسه.
 *
 * القيم هي وسيط الإضاءة الفعلي لكل درجة عبر تسع عائلات ملوّنة في
 * `tokens.css` (`signal`·`ember`·`measure`·`inspect`·`success`·`warning`·
 * `danger`·`info`، واستُبعدت `ink` من القياس لأن تشبّعها شبه صفري فزاويتها
 * ضجيج لا معنى له — لكن إضاءتها توافقت مع البقية ضمن الانحراف نفسه). انظر
 * الجدول في ترويسة الملفّ للأرقام كاملةً، والانحراف المعياري لكل درجة بين
 * 0.04 و0.13 نقطة مئوية فقط — أي أنها شبكة واحدة فعلًا لا صدفة.
 */
const SCALE_LIGHTNESS: readonly number[] = [
  0.97525, 0.94532, 0.88992, 0.82004, 0.74045, 0.65541, 0.57459, 0.49039, 0.40027, 0.31032, 0.24077,
]

/** درجة واحدة من السلّم — إحداثياتها الحقيقية، وحكم صريح على مداها. */
export interface ScaleStop {
  readonly step: number
  /** إحداثيات OKLCH الحقيقية — **قبل** أي قصّ، على نمط `ColourReading.oklch`. */
  readonly oklch: Oklch
  /** القيمة السداسية بعد التقريب إلى بايت — ما يُرسَم فعلًا. */
  readonly hex: string
  /**
   * هل هذه الدرجة داخل مدى sRGB فعلًا؟
   *
   * **تُعلَن ولا تُخفى** (نفس مبدأ `ColourReading.inSrgb`، انظر ترويسة
   * `formats.ts`): لون أساس فوق حافة sRGB (خارج المدى أصلًا، أو مشبَّع
   * جدًّا قرب طرفي السلّم) يُنتج درجاتٍ خارج المدى أيضًا، وهذه أمانة لا عيب
   * يُستَر — القيمة الحقيقية باقية في `oklch`، و`hex` تقريبها المعروض.
   */
  readonly inSrgb: boolean
}

/**
 * أقصى تشبّع ممكن داخل sRGB عند إضاءة وزاوية معيّنتين — حافة المدى نفسها،
 * لا حدًّا نظريًّا. `clampChroma` يبدأ من قيمة تشبّع مضمونة **خارج** المدى
 * (هنا `1` — أعلى من أقصى تشبّع OKLCH ممكن في sRGB بمقدار ثلاثة أمثال، انظر
 * الجدول في ترويسة الملفّ حيث لا تتجاوز أعلى قيمة فعلية ‎0.28‎) ويبحث
 * ثنائيًّا حتى يجد أعلى تشبّع لا يزال داخل المدى — وهي بالضبط الطريقة التي
 * وُلِّدت بها درجات `tokens.css`، مُثبَتة رقميًّا في ترويسة الملفّ.
 */
const CHROMA_SEARCH_SEED = 1

function maxChromaInSrgb(l: number, h: number): number {
  return clampChroma({ mode: 'oklch', l, c: CHROMA_SEARCH_SEED, h }, 'oklch', 'rgb').c
}

/** تشبّع أقل من هذا يُعامَل صفرًا — يمنع القسمة على صفر قرب الرماديات الخالصة. */
const CHROMA_EPSILON = 1e-6

/*
 * **البناء من إحداثيات محسوبة يمرّ بـ`fromOklch` في `formats.ts`.**
 *
 * كان هنا في أوّل كتابة بناءُ نصّ `oklch(…%…)` ثم إعادة تحليله بـ`readColour`
 * — دورةٌ نصّية كاملة لبيانات موجودة عددًا، عشر مرّات لكل سلّم. وأمسكها
 * حارس عقد التوكنز (`verify-tokens.mjs`) بوصفها «قيمة لونية حرفية»، وكان
 * إسكاته بـ`rasd-allow-literal` ممكنًا — لكن الحارس كان محقًّا في جوهر
 * الأمر: السلسلة لم تكن ضرورية أصلًا. فصُدِّرت `fromOklch` من `formats.ts`
 * (تمرّ بـ`fromColor` الداخلية نفسها التي تمرّ بها `readColour`، فالقصّ
 * والتقريب وحكم `inSrgb` تبقى في موضع واحد)، وزال السببان معًا.
 */

/** أقرب فهرس في `SCALE_LIGHTNESS` إلى إضاءة معيّنة — تعادلٌ يُحسم لصالح الأخفّ. */
function nearestLightnessIndex(l: number): number {
  let best = 0
  let bestDistance = Math.abs(l - SCALE_LIGHTNESS[0]!)
  for (let i = 1; i < SCALE_LIGHTNESS.length; i++) {
    const distance = Math.abs(l - SCALE_LIGHTNESS[i]!)
    if (distance < bestDistance) {
      bestDistance = distance
      best = i
    }
  }
  return best
}

/**
 * سلّم 50→950 من لون أساس واحد، على شبكة الإضاءة المشتركة أعلاه.
 *
 * **قرار 1 — أين يقع الأساس في السلّم؟ بأقرب درجة بإضاءته، لا عند 500
 * دائمًا.** لو ثُبِّت الأساس عند 500 قسرًا لتغيّرت إضاءته الفعلية لتطابق
 * شبكة 500 (65.5%) — فلونٌ فاتح جدًّا (بيج فاتح، إضاءته 92%) يُسحَب لأسفل
 * 27 نقطة قبل أن يبدأ السلّم أصلًا، وسلّمه كلّه ينزاح غامقًا رغم أن مصدره
 * فاتح. والإسناد بأقرب درجة يحفظ اللون **كما اختاره المستخدم بالضبط** في
 * موضعه الطبيعي على الشبكة (تلك الدرجة تحمل `oklch` الأساس حرفيًّا، بلا
 * أي تقريب لإضاءته)، وباقي الدرجات تُبنى حوله. وهذا مضمونٌ رياضيًّا ألّا
 * يكسر اتساق الإضاءة: أقرب فهرس لإضاءة `l` تقع دائمًا بين قيمتَي جارتيه في
 * الشبكة (تعريف «الأقرب» نفسه)، فتبقى القيم الإحدى عشرة مرتّبة تنازليًّا
 * حتى حين تحلّ إضاءة الأساس الفعلية محلّ قيمة الشبكة عند درجته.
 *
 * **قرار 2 — التشبّع عند الطرفين: يُقصّ على حافة sRGB لتلك الإضاءة
 * والزاوية، مضروبًا في نسبة تشبّع الأساس.** أثبتت ترويسة الملفّ أن كل
 * درجة في `tokens.css` تساوي حافة sRGB عند (`l`,`h`) بالضبط — أي أن
 * `tokens.css` نفسه لا يستعمل نسبة ثابتة، بل يملأ المدى كلّه في كل درجة.
 * لكن ذلك افترض أساسًا مُختارًا مشبَّعًا بالفعل. أساسٌ اختاره المستخدم قد
 * يكون أقل تشبّعًا عمدًا (لون هادئ)، فملء الحافة في كل درجة كان سيتجاهل
 * ذلك الاختيار ويُخرج سلّمًا صارخًا من مدخل هادئ. فبدل ملء الحافة دائمًا:
 * `نسبة = تشبّع الأساس ÷ أقصى تشبّع ممكن عند إضاءته وزاويته هو`، وهذه
 * النسبة تُطبَّق على حافة كل درجة أخرى. أساسٌ يقع أصلًا على الحافة (كأي
 * درجة في `tokens.css`) يعطي `نسبة = 1` فيُنتج **السلوك المُثبَت فعليًّا
 * أعلاه بالضبط** — والدالّة تعمّم ذلك السلوك بدل أن تُقلِّده حرفيًّا فقط
 * عند تلك الحالة الخاصّة.
 *
 * **قرار 3 — الزاوية ثابتة عبر السلّم كلّه** (زاوية الأساس نفسها)، بلا
 * انحراف الطباعة السداسية الذي يظهر في `tokens.css` (1°–3°، أثر تقريب لا
 * تصميم — انظر ترويسة الملفّ)، فهذا أدقّ من المصدر نفسه لا أقلّ منه.
 *
 * **قرار 4 — الرماديات (`c === 0`).** أقصى تشبّع عند أي زاوية لا يُغيّر
 * النتيجة إن كانت النسبة صفرًا: `صفر × أيّ حافة = صفر`. فسلّم من رمادي
 * أساس رماديٌّ بالكامل — لا اختراع لزاوية لم يخترها أحد. وعند إضاءة 0 أو 1
 * تمامًا (أسود/أبيض خالصان) أقصى تشبّع ممكن هو صفر بحكم الهندسة نفسها
 * (لا مجال تشبّع عند حواف مكعّب sRGB)، فيُتجنَّب القسمة على صفر بإرجاع
 * نسبة صفرية مباشرةً دون حاجة لحالة خاصّة إضافية.
 *
 * **الخروج عن مدى sRGB مُعلَن لا مخفيّ**: انظر `ScaleStop.inSrgb`.
 */
export function generateScale(base: ColourReading): readonly ScaleStop[] {
  const { l: baseL, c: baseC, h: baseH } = base.oklch

  const anchorIndex = nearestLightnessIndex(baseL)
  const baseMaxChroma = maxChromaInSrgb(baseL, baseH)
  const saturationRatio = baseMaxChroma > CHROMA_EPSILON ? baseC / baseMaxChroma : 0

  return SCALE_STEPS.map((step, i) => {
    if (i === anchorIndex) {
      return { step, oklch: base.oklch, hex: formatColour(base).hex, inSrgb: base.inSrgb }
    }
    const l = SCALE_LIGHTNESS[i]!
    const c = Math.max(0, maxChromaInSrgb(l, baseH) * saturationRatio)
    const reading = fromOklch(l, c, baseH)
    return { step, oklch: reading.oklch, hex: formatColour(reading).hex, inSrgb: reading.inSrgb }
  })
}

/**
 * خطوة الإضاءة الافتراضية لـ`lighten`/`darken` حين لا تُمرَّر `amount`.
 *
 * وسيط الفجوات العشر بين درجات `SCALE_LIGHTNESS` المتجاورة (بالنسبة
 * المئوية): `2.99، 5.54، 6.96، 6.99، 7.96، 8.08، 8.42، 8.50، 9.00، 9.01` —
 * مرتّبةً، الوسيط متوسط العنصرين الخامس والسادس: `(7.96 + 8.08) / 2 =
 * 8.02`. فخطوة واحدة افتراضية تساوي **فجوة درجة واحدة نموذجية على السلّم
 * نفسه** لا رقمًا مُخترَعًا بمعزل عنه.
 */
const DEFAULT_LIGHTNESS_STEP = 0.0802

/**
 * نسبة التشبّع الافتراضية لـ`saturate`/`desaturate` حين لا تُمرَّر
 * `amount` — 20%. خطوة نسبية لا مطلقة عمدًا: مدى التشبّع المفيد يختلف
 * جذريًّا بين الزوايا (0.03 عند بعض الزوايا الباهتة قرب الأبيض، وأكثر من
 * 0.27 عند زوايا حادّة كالأرجواني — انظر جدول ترويسة الملفّ)، فخطوة مطلقة
 * واحدة كانت ستمحو تشبّع بعض الألوان وتكاد لا تُحسّ في بعضها الآخر. و20%
 * اختيارٌ مريح لا نتيجة قياس دقيق (بخلاف `DEFAULT_LIGHTNESS_STEP` المقيسة
 * من الشبكة نفسها) — لكنها قريبة من نسبة التغيّر الملحوظة فعلًا بين درجات
 * متجاورة غامقة في `tokens.css` (‎12%–18%‎ تقريبًا).
 */
const DEFAULT_CHROMA_RATIO_STEP = 0.2

/**
 * أفتح — يزيد الإضاءة فقط؛ التشبّع والزاوية كما هما حرفيًّا.
 *
 * لو أُعيد اشتقاق التشبّع إلى حافة sRGB الجديدة لكان هذا هو سلوك
 * `generateScale` نفسه لا تعديلًا مفردًا مستقلًّا — و`§6.12` تسرد الأربعة
 * والسلّم كقدرات منفصلة. فالتعديل هنا **قناة واحدة فقط**، وقد يخرج الناتج
 * عن مدى sRGB عند إضاءة عالية جدًّا مع تشبّع كان يناسب إضاءة أدنى — وهذا
 * مُعلَن في `inSrgb` الناتجة عن `readColour`، لا مخفيّ.
 */
export function lighten(c: ColourReading, amount = DEFAULT_LIGHTNESS_STEP): ColourReading {
  return fromOklch(clamp01(c.oklch.l + amount), c.oklch.c, c.oklch.h, c.alpha)
}

/** أغمق — نظير `lighten` بالاتجاه المعاكس، القناة نفسها فقط. */
export function darken(c: ColourReading, amount = DEFAULT_LIGHTNESS_STEP): ColourReading {
  return fromOklch(clamp01(c.oklch.l - amount), c.oklch.c, c.oklch.h, c.alpha)
}

/**
 * أكثر تشبّعًا — يضرب التشبّع الحالي في `(1 + amount)`؛ الإضاءة والزاوية
 * كما هما.
 *
 * **لماذا نسبيًّا من التشبّع الحالي، لا استيفاءً نحو حافة sRGB؟** كان
 * الخيار الأول المدروس هو الاستيفاء نحو `maxChromaInSrgb(l, h)` (نفس آلة
 * `generateScale`) — لكنه ينكسر تمامًا مع لون **خارج** مدى sRGB أصلًا
 * (`inSrgb: false`؛ ألوان P3 مثلًا، تصلها الأداة عبر CSS كما توثّق ترويسة
 * `formats.ts`): إن كان تشبّعه الحقيقي **أعلى** من حافة sRGB، فالفرق
 * `(الحافة − التشبّع)` سالب، والاستيفاء نحوه بمقدار موجب **يُنقص** التشبّع
 * بدل أن يزيده — دالّة اسمها «أكثر تشبّعًا» تُخفّض التشبّع فعليًّا. الضرب
 * النسبي لا ينعكس اتجاهه أبدًا مهما كان موضع اللون من حافة أيّ مدى.
 */
export function saturate(c: ColourReading, amount = DEFAULT_CHROMA_RATIO_STEP): ColourReading {
  return fromOklch(c.oklch.l, Math.max(0, c.oklch.c * (1 + amount)), c.oklch.h, c.alpha)
}

/**
 * أقل تشبّعًا — يضرب التشبّع الحالي في `(1 − amount)`، بحدّ أدنى صفر؛
 * الإضاءة والزاوية كما هما.
 *
 * **الرماديات (`c === 0`): تعديلٌ محايد صراحةً — لا `saturate` ولا
 * `desaturate` يُخرجان رماديًّا من حياديته.** `desaturate` تافه المعنى هنا
 * (‎0 × (1 − amount) = 0‎). و`saturate` كذلك بالضرب النسبي نفسه
 * (‎0 × (1 + amount) = 0‎) — وهذا مقصود لا قصور: الزاوية `h` لرمادي خالص
 * بلا معنى أصلًا (تُعرَّف صفرًا اصطلاحًا في `formats.ts`)، فـ«أكثر تشبّعًا»
 * لا يملك زاويةً حقيقية يتّجه نحوها. البديل المرفوض — الاستيفاء نحو
 * `maxChromaInSrgb(l, h=0)` — كان سيخترع صبغة حمراء من رمادي محض لمجرّد
 * أن الزاوية الاصطلاحية صفر تصادف زاوية الأحمر، وهو بالضبط ما ترفضه هذه
 * الدالّة بالضرب النسبي.
 */
export function desaturate(c: ColourReading, amount = DEFAULT_CHROMA_RATIO_STEP): ColourReading {
  return fromOklch(c.oklch.l, Math.max(0, c.oklch.c * (1 - amount)), c.oklch.h, c.alpha)
}
