/** الحالات الأربع، ورابعتها «لا قياس بعد» — حالة مصمَّمة لا نقص يُخفى. */
export type DiffStatus = 'unmeasured' | 'identical' | 'minor' | 'major'

/** عندها فما فوق: «فروق كبيرة». كسرٌ من 0 إلى 1 كـ`LiveDiff.diffRatio` نفسه، لا نسبة مئوية. */
const MAJOR_MIN_RATIO = 0.05

/**
 * يصنِّف كسر الفرق (0–1) إلى رقاقة حالة. `null` — ولا قياس لهذا المقاس بعد.
 *
 * **القيم الشاذّة تُقصَّ إلى الطرف الأقرب لا تُرفض**، نفس معاملة
 * `classifyViewport` لعرضٍ غير موجب: كسرٌ سالب مستحيل من `computeDiff`
 * (عدٌّ مقسومٌ على عدّ)، فيُقرأ «لا فرق»؛ وما فوق الواحد يقع في «كبيرة»
 * بالمقارنة نفسها. أمّا غير المنتهي (`NaN`/`Infinity`) فليس قيمةً قُصَّت
 * بل قياسٌ لم يقع — فيُقرأ «لم يُقارَن» لا يُصنَّف كذبًا.
 */
export function classifyDiffStatus(ratio: number | null): DiffStatus {
  if (ratio === null || !Number.isFinite(ratio)) return 'unmeasured'
  if (ratio <= 0) return 'identical'
  return ratio >= MAJOR_MIN_RATIO ? 'major' : 'minor'
}

