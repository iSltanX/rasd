/** الدقائق بالأرقام الهندية — عدٌّ بشري لا قيمة تقنية. */
const minutes = new Intl.NumberFormat('ar-u-nu-arab')

export function failureMessage(error: SendError): string {
  const base = TEXT[error.failure]
  if (error.failure === 'rate-limited' && error.retryAfterSeconds !== undefined) {
    const m = Math.max(1, Math.ceil(error.retryAfterSeconds / 60))
    const when =
      m === 1
        ? 'دقيقة'
        : m === 2
          ? 'دقيقتين'
          : `${minutes.format(m)} ${m <= 10 ? 'دقائق' : 'دقيقة'}`
    return `${base} أعد المحاولة بعد ${when}.`
  }
  return base
}
