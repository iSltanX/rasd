/**
 * نوع اللقطة من مصدر الأمر.
 *
 * **لماذا وحدة مستقلّة لسطر واحد:** النوع يُكتب في `CaptureRecord.kind` ويُفهرَس
 * في IndexedDB (`captures.kind`)، وعليه تقوم تصفية المكتبة بالنوع في المرحلة 18.
 * وخطأ هنا لا يظهر عند وقوعه بل بعد شهور من الاستعمال، في صورة تصفية تكذب على
 * بيانات لا تُصلَح إلا بترحيل. فالقرار يُفصَل عن طبقة التشغيل ويُختبَر.
 *
 * قِيس أن الفرع كان يُسجّل `'area'` لكل التقاط عنصر لأن الدالّة المشتركة كانت
 * تشتقّ النوع من **وجود مستطيل** وحده، ووجود المستطيل لا يميّز المصدر: أداة
 * المنطقة وأداة العنصر كلتاهما تُسلّم مستطيلًا. صُحِّح في جولة صيانة الخطة.
 */

import type { ViewportRect } from '@/shared/geometry'
import type { CaptureKind } from '@/shared/storage/schema'

/**
 * مصدر أمر الالتقاط داخل الصفحة.
 *
 * `full-page` و`window` ليسا هنا: الأولى تُقاد من الـservice worker بمسارها
 * الخاصّ (ADR 0010)، والثانية مؤجَّلة إلى 1.1.
 */
export type CaptureSource = 'area' | 'element'

/**
 * `rect` هو الفارق بين لقطة مقصوصة ولقطة الجزء الظاهر كاملًا: `null` يعني «لا
 * قصّ»، وهي حالة `viewport` أيًّا كان المصدر — الالتقاط الفوري والمؤجَّل كلاهما
 * يمرّ من وضع «منطقة» بلا تحديد.
 *
 * ومتى وُجد المستطيل فالنوع هو **المصدر** لا تخمينًا عنه.
 */
export function captureKindFor(
  source: CaptureSource,
  rect: ViewportRect | null,
): Extract<CaptureKind, 'area' | 'element' | 'viewport'> {
  return rect ? source : 'viewport'
}
