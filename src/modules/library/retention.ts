/**
 * الحذف الدوري باختيار المستخدم — `§11` «حذف السجلّ تلقائيًا بعد مدّة».
 *
 * **وهو غير تطهير المهملات، ولا يُخلط به.** `trash.ts` يطهّر ما حذفه
 * المستخدم بيده وانقضت مهلة استعادته — سياسةُ نظامٍ لم يطلبها أحد، ولذلك
 * تعمّد ألّا يكون لها مؤقّت خلفي. أمّا هنا فالمدّة **اختيارٌ صريح كتبه
 * المستخدم في شاشة الخصوصية**، ووعدُ الشاشة نصُّه «احذف تلقائيًا اللقطات
 * الأقدم من ٣٠ يومًا». وعدٌ لا يُنفَّذ إلّا حين يفتح المكتبة ليس تلقائيًّا:
 * من اختار الحذف ولا يفتح المكتبة لا يُحذف عنه شيء أبدًا، فيصير الضابط
 * وعدًا لا سلوكًا. فالمنبّه هنا **شرط صدق الوعد**، لا تجاوزٌ لقاعدة
 * `trash.ts` — وقد صُحِّح نصّ تلك القاعدة في الالتزام نفسه كي يبقى الفارق
 * مكتوبًا حيث يُقرأ.
 *
 * **والحذف نهائيّ لا إلى المهملات.** «احذف بعد ٧ أيام» تصير فعليًّا ٣٧ يومًا
 * لو مرّ السجلّ بمهملات احتفاظها ٣٠ — وذلك خُلفٌ لنصّ الشاشة لا تشدّدٌ
 * زائد في الأمان.
 *
 * **والمميَّزة مستثناة** — نصّ التصميم حرفيًّا: «ينطبق على غير المميّزة فقط».
 *
 * `now` مُمرَّر لا مُشتقّ داخل الدالّة — نفس نمط `trash.ts` حرفًا بحرف،
 * فتبقى قابلة للاختبار بلا مؤقّتات مزيَّفة.
 */

import { ok, type Result } from '@/shared/result'
import { captures } from '@/shared/storage/repository'

import { purgeCapture } from './trash'

const MS_PER_DAY = 24 * 60 * 60 * 1000

/** المدد التي يعرضها الضابط — مطابقة لـ`picklist` في مخطّط الإعدادات. */
export type RetentionDays = 0 | 7 | 30 | 90

/**
 * يحذف كل لقطة أقدم من `days` نهائيًّا — عدا المميَّزة.
 *
 * **يُستعمل الفهرس لا المسح الكامل.** `purgeExpired` المجاور يقرأ
 * `captures.getAll()` لأن معياره (`trashedAt`) بلا فهرس. أمّا `createdAt`
 * فعليه فهرس حقيقي منذ النسخة 1 من قاعدة البيانات، و`byIndex` يقبل
 * `IDBKeyRange` أصلًا — فالمدى يحصر المقروء في المستحقّ وحده بدل جرّ
 * المكتبة كلّها إلى الذاكرة في كل دورة، وهذه الدالّة تعمل في الخلفية بلا
 * مستخدم يراقب. وهذا أوّل استعمال لـ`IDBKeyRange` في المشروع.
 *
 * والترشيح على `favorite` يبقى في الذاكرة: لا فهرس عليه (خمسة فهارس على
 * `captures`: ‏`createdAt` · `projectId` · `origin` · `kind` · `status`)،
 * وإضافة فهرس سادس ترفع نسخة القاعدة وتُلزم ترحيلًا — ثمنٌ لا يقابله
 * مكسب على مجموعةٍ **حصرها المدى أصلًا**.
 *
 * التسلسل لا يتوازى، لنفس تعليل `purgeExpired`: فشلٌ وسط `Promise.all` يترك
 * حالة الحذف غامضة. والعدد المُرجَع هو ما حُذف فعلًا لا ما كان مستحقًّا.
 */
export async function retentionSweep(now: number, days: RetentionDays): Promise<Result<number>> {
  if (days === 0) return ok(0)

  const cutoff = now - days * MS_PER_DAY
  const due = await captures.byIndex('createdAt', IDBKeyRange.upperBound(cutoff, true))
  if (!due.ok) return due

  let purged = 0
  for (const record of due.value) {
    if (record.favorite) continue
    const removed = await purgeCapture(record.id)
    if (!removed.ok) return removed
    purged += 1
  }
  return ok(purged)
}
