/**
 * تطبيع النص العربي للبحث — إزالة التشكيل وتوحيد الألف والهاء (§10.4).
 *
 * التطبيع **دلالي لا شكلي**: البحث يقارن ما يقصده المستخدم لا رسم الحرف
 * حرفيًا. من يكتب «مراجعة» يتوقّع أن يجد «مُراجعة» رغم التشكيل — والتشكيل
 * زخرفة نطقية لا جزء من الهوية النصّية للكلمة. ومن يكتب «الالتقاطة» بهاء
 * عادية يتوقّع أن يجد «الالتقاطة» بتاء مربوطة، لأن الحرفين يُنطقان معًا في
 * وقف الكلام ويختلطان في الكتابة السريعة.
 *
 * كل نطاق حروف أدناه مذكورٌ برمزه بترميز يونيكود نصًّا بجوار تعريفه — لأن
 * علامات التشكيل حروف تركيبية (combining marks) تُعرض ملتصقة بلا حامل خارج
 * سياقها، فتصير غامضة بصريًا في مصدر الشيفرة. ومُتحقَّقٌ منها برمجيًا بفكّ
 * نقاط الشيفرة حرفًا حرفًا لا بصريًا وحسب، في `normalize.test.ts`.
 *
 * `modules/` منطق خالص: لا DOM ولا مؤقّتات — دالتان محضتان بلا أثر جانبي.
 */

/**
 * حركات وتنوين وشدّة وسكون: المدى الأساسي فتحتان-فتحة-ضمّتان-ضمّة-كسرتان-
 * كسرة-شدّة-سكون، زائد ألف خنجرية علوية، زائد علامات تجويد قرآنية إضافية
 * تظهر أحيانًا في نصوص منسوخة من مصاحف رقمية.
 */
const DIACRITICS = /[ً-ٰٟۖ-ۭ]/gu

/** الألف بصورها الثلاث الملموزة — مدّة، همزة فوق، همزة تحت — إلى ألف عادية. */
const ALEF_VARIANTS = /[آأإ]/gu
const ALEF = 'ا'

/** تاء مربوطة إلى هاء — توحيد الهاء المطلوب نصًّا في §10.4. */
const TA_MARBUTA = /ة/gu
const HEH = 'ه'

/**
 * يطبِّع نصًّا عربيًا للمقارنة: يزيل التشكيل، ويوحّد الألف والهاء، ويخفض حالة
 * اللاتيني (كي تُطابق قيم HEX بلا حساسية لحالة الأحرف).
 */
export function normalizeArabic(text: string): string {
  return text
    .replace(DIACRITICS, '')
    .replace(ALEF_VARIANTS, ALEF)
    .replace(TA_MARBUTA, HEH)
    .toLowerCase()
}

/**
 * مطابقة جزئية بعد التطبيع: هل يحوي `haystack` `needle` في أي موضع؟
 *
 * استعلامٌ فارغ يطابق كل شيء — شريط بحث فارغ لا يُصفّي، لا يُخفي.
 */
export function matchesQuery(haystack: string, needle: string): boolean {
  const normalizedNeedle = normalizeArabic(needle.trim())
  if (!normalizedNeedle) return true
  return normalizeArabic(haystack).includes(normalizedNeedle)
}
